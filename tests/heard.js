"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const { heardProposal } = require('../tools/heard');
const proposal = () => ({version:'lsg', bookId:43, chapter:3, verse:16, verseEnd:16, method:'reference', confidence:1, end:Date.now(), text:'FAUX', reference:'FAUX', heard:'Jean 3 verset 16'});
let p = heardProposal(proposal());
assert.equal(p.reference, 'Jean 3:16');
assert.match(p.text, /Dieu a tant aimé/);
for (const bad of [{confidence:.89}, {confidence:NaN}, {verse:99,verseEnd:99}, {version:'../../x'}, {version:'cra'}, {method:'invented'}, {end:Date.now()-10000}, {end:Date.now()+5000}, {verse:0,verseEnd:16}])
  assert.equal(heardProposal({...proposal(), ...bad}), null);
const html = fs.readFileSync(path.join(__dirname, '../control_panel.html'), 'utf8');
const dom = new JSDOM(html, {runScripts:'outside-only', url:'http://127.0.0.1:18760/control_panel.html'});
const w = dom.window;
w.VerseObs = {};
w.eval(fs.readFileSync(path.join(__dirname, '../assets/js/control/heard-verse.js'), 'utf8'));
const callbacks = [], loaded = [], sent = [];
let working = {id:'lsg',name:'Louis Segond'};
const link = new w.VerseObs.HeardVerse({workingVersion:()=>working,channel:{onMessage: cb=>callbacks.push(cb),send: x=>sent.push(x)},load: x=>{loaded.push(x);return Promise.resolve(true);},openConnections:()=>{}});
function receive(x){callbacks.forEach(cb=>cb(x));}
link.setRelay(true);
receive({type:'caption_status',engine:true,state:{status:'listening'},session:'one'});
receive({type:'heard_verse',proposal:p,session:'one',ts:Date.now()});
assert.equal(w.document.getElementById('heard-reference').textContent, 'Jean 3:16');
assert.equal(loaded.length,0,'La réception ne touche jamais la sélection');
assert.equal(sent.length,0,'La carte ne dispose d’aucune commande d’antenne');
w.document.getElementById('heard-load').focus();
receive({type:'heard_verse',proposal:{...p,reference:'Jean 3:17',verse:17,verseEnd:17},session:'one',ts:Date.now()});
assert.equal(w.document.getElementById('heard-reference').textContent,'Jean 3:16','ne remplace pas une cible focalisée');
assert.equal(w.document.getElementById('heard-next').hidden,false,'la nouvelle proposition reste accessible');
w.document.getElementById('heard-next').click();
assert.equal(w.document.getElementById('heard-reference').textContent,'Jean 3:17');
w.document.getElementById('heard-load').click();
assert.equal(loaded.length,1);
assert.equal(sent.length,0);
receive({type:'heard_clear'});
assert.equal(w.document.getElementById('heard-proposal').hidden,true);
receive({type:'heard_verse',proposal:{...p,confidence:.5},session:'one'});
assert.equal(w.document.getElementById('heard-proposal').hidden,true);
receive({type:'heard_verse',proposal:{...p,ready:Date.now()-61000},session:'one'});
assert.equal(w.document.getElementById('heard-proposal').hidden,true);
receive({type:'heard_verse',proposal:p,session:'one',ts:Date.now()});
working={id:'nbs',name:'Nouvelle Bible Segond'}; // changement avant notification
w.document.getElementById('heard-load').click();
assert.equal(loaded.length,1,'un clic ne peut accepter une annonce périmée');
assert.match(w.document.getElementById('heard-explanation').textContent,/LSG remplace votre Nouvelle Bible Segond/);
w.document.getElementById('heard-load').click();
assert.equal(loaded.length,2,'second clic après annonce actualisée');
link.setRelay(false);
assert.equal(w.document.getElementById('heard-proposal').hidden,true);
dom.window.close();
console.log('ok   Verset entendu : validation locale, abstention, pas d’antenne, arrêt, expiration, déconnexion');
