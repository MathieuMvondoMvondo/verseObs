// Vrais Chromium + relais WebSocket + contexte OBS isolé. Aucun test ignoré.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {WebSocket} from 'ws';
const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const {createServer} = require('../tools/server');
if (!process.env.PLAYWRIGHT_CORE || !process.env.CHROMIUM) throw new Error('PLAYWRIGHT_CORE et CHROMIUM requis');
const {chromium} = await import(process.env.PLAYWRIGHT_CORE);
const port = Number(process.env.HEARD_PORT || 18764), base = `http://127.0.0.1:${port}`;
const out = path.join(ROOT, 'artifacts/verset'); fs.mkdirSync(out,{recursive:true});
const server = createServer(port);
await new Promise(r=>server.listen(port,'127.0.0.1',r));
const browser = await chromium.launch({executablePath:process.env.CHROMIUM,args:['--no-sandbox']});
const ctx = await browser.newContext({viewport:{width:1280,height:1000}});
const obsctx = await browser.newContext({viewport:{width:1920,height:1080}});
const page = await ctx.newPage(), obs = await obsctx.newPage();
const errors=[], commands=[], results=[];
page.on('pageerror', e=>errors.push(e.message));obs.on('pageerror',e=>errors.push(e.message));
const ws = new WebSocket(`ws://127.0.0.1:${port}/verseobs-relay`,{headers:{Origin:base}});
await new Promise(r=>ws.once('open',r));
ws.on('message', raw=>commands.push(JSON.parse(raw)));
let n=0, heartbeat;
const send = m=>ws.send(JSON.stringify({id:'heard-test-'+ ++n,ts:Date.now(),...m}));
const state={status:'listening',listenId:'browser-heard',verses:'11 versions disponibles ; Crampon exclu (numérotation incohérente).'};
const say = (extra={})=>send({type:'heard_verse',proposal:{listenId:'browser-heard',version:'lsg',bookId:45,chapter:6,verse:23,verseEnd:23,method:'reference',confidence:1,end:Date.now()-900,heard:'Il nous dit ça dans Romains 6, 23.',...extra}});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const program=()=>commands.filter(x=>['show_verse','show_text','hide'].includes(x.type));
try {
  await obs.goto(base+'/browser_source.html');
  await page.goto(base+'/control_panel.html');
  await page.waitForSelector('.chapter-verse');
  send({type:'caption_engine',state});
  heartbeat=setInterval(()=>send({type:'caption_engine',state}),1000);
  await page.waitForFunction(()=>document.querySelector('#heard-state').textContent==='À l’écoute');
  await sleep(3300); // capture après disparition du toast de démarrage
  const preparedTop=await page.locator('#preview-ref').evaluate(e=>e.getBoundingClientRect().top);
  const before=program().length;
  say();
  await page.waitForFunction(()=>document.querySelector('#heard-reference').textContent==='Romains 6:23');
  assert.match(await page.locator('#heard-text').textContent(),/salaire du péché/);
  assert.equal(await page.locator('#preview-ref').textContent(),'Jean 3:16');
  assert.equal(program().length,before);
  assert.equal(await obs.locator('.verse-card.visible').count(),0);
  assert.ok(Math.abs(await page.locator('#preview-ref').evaluate(e=>e.getBoundingClientRect().top)-preparedTop)<=1,'le passage préparé ne bouge pas');
  await page.screenshot({path:path.join(out,'carte-studio.png'),fullPage:false});
  results.push('réception : texte local réel, sélection et antenne inchangées');
  await page.locator('#heard-load').click();
  await page.waitForFunction(()=>document.querySelector('#preview-ref').textContent==='Romains 6:23');
  assert.equal(program().length,before);
  results.push('charger : aperçu seul, aucune commande SHOW');
  // Diffusion exclusivement par le bouton existant, puis nouvelle proposition.
  await page.keyboard.press('Control+Enter');
  await obs.waitForFunction(()=>document.querySelector('#verse-container')?.textContent.includes('salaire du péché'));
  const afterManual=program().length;
  say({bookId:43,chapter:3,verse:16,verseEnd:16,method:'lexical',confidence:.99,heard:'Car Dieu a tant aimé le monde…'});
  await sleep(100);
  if (await page.locator('#heard-next').isVisible()) await page.locator('#heard-next').click();
  await page.waitForFunction(()=>document.querySelector('#heard-reference').textContent==='Jean 3:16');
  await page.locator('#heard-load').click();
  await page.waitForFunction(()=>document.querySelector('#preview-ref').textContent==='Jean 3:16');
  assert.equal(program().length,afterManual);
  assert.match(await obs.locator('#verse-container').textContent(),/salaire du péché/);
  results.push('antenne déjà occupée : ni réception ni chargement ne la remplacent');
  // Course réelle : une seconde traduction retardée ne doit pas diffuser
  // la nouvelle plage préparée par Verset entendu à la place du clic précédent.
  let delayed;
  await page.route('**/sem.json',route=>{delayed=route;});
  await page.locator('#bilingual-toggle').click();
  await page.locator('#secondary-version').selectOption('sem');
  for(let i=0;i<100&&!delayed;i++) await sleep(20);
  assert.ok(delayed,'seconde version effectivement retenue');
  await page.locator('.chapter-verse[data-verse="17"]').click();
  say({bookId:43,chapter:3,verse:17,verseEnd:18});
  await page.waitForFunction(()=>document.querySelector('#heard-reference').textContent==='Jean 3:17-18');
  await page.locator('#heard-load').click();
  await page.waitForFunction(()=>document.querySelector('#preview-ref').textContent==='Jean 3:17-18');
  await delayed.continue();
  await page.waitForFunction(()=>!document.querySelector('#btn-show').disabled);await sleep(300);
  assert.equal(program().length,afterManual,'aucun SHOW différé de la proposition');
  assert.match(await obs.locator('#verse-container').textContent(),/salaire du péché/);
  await page.locator('#bilingual-toggle').click();
  results.push('enchaînement + deuxième version retardée : la proposition reste en aperçu');
  await page.locator('#heard-dismiss').click();
  say({confidence:.6}); await sleep(100);
  assert.equal(await page.locator('#heard-proposal').isVisible(),false);
  results.push('sous le seuil : aucune carte');
  say({bookId:46,chapter:13,verse:0,verseEnd:0});
  await page.waitForFunction(()=>document.querySelector('#heard-reference').textContent==='1 Corinthiens 13');
  assert.match(await page.locator('#heard-explanation').textContent(),/Chapitre seul/);
  await page.locator('#heard-load').click();
  await page.waitForFunction(()=>document.querySelector('#preview-ref').textContent==='1 Corinthiens 13:1');
  assert.equal(program().length,afterManual);
  results.push('chapitre seul : annonce explicite, ouvre v.1 sans diffusion');
  for (const width of [920,600,360,320]) {
    await page.setViewportSize({width,height:900});
    await page.locator('#heard-explanation').evaluate(e=>e.scrollIntoView({block:'center'}));
    assert.equal(await page.locator('#heard-explanation').evaluate(e=>{
      const r=e.getBoundingClientRect(),c=document.querySelector('#heard-card').getBoundingClientRect();
      return r.top>=c.top && r.bottom<=c.bottom && r.top>=0 && r.bottom<=innerHeight && e.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2));
    }),true,'avertissement chapitre seul visible et non masqué à '+width);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'pas de débordement à '+width);
    await page.screenshot({path:path.join(out,`carte-${width}.png`)});
  }
  results.push('920/600/360/320 px : carte lisible, pas de débordement horizontal');
  // Une requête primaire lente est remplacée par la carte, sans verrou orphelin.
  await page.setViewportSize({width:1280,height:1000});
  let primary;
  await page.route('**/nbs.json',route=>{primary=route;});
  await page.locator('#version-select').focus();say();
  await page.waitForFunction(()=>document.querySelector('#heard-reference').textContent==='Romains 6:23');
  await page.locator('#version-select').selectOption('nbs');
  for(let i=0;i<100&&!primary;i++)await sleep(20);
  assert.ok(primary);
  assert.match(await page.locator('#heard-explanation').textContent(),/LSG remplace votre Nouvelle Bible Segond/);
  await page.locator('#heard-load').click();
  await page.waitForFunction(()=>!document.querySelector('#version-select').disabled);
  assert.equal(await page.locator('#version-select').inputValue(),'lsg');
  await primary.continue();await sleep(150);await page.unroute('**/nbs.json');
  assert.equal(await page.locator('#version-select').isEnabled(),true);
  await page.locator('#version-select').selectOption('nbs');
  await page.waitForFunction(()=>!document.querySelector('#version-select').disabled);
  assert.match(await page.locator('#heard-explanation').textContent(),/LSG remplace votre Nouvelle Bible Segond/);
  await page.locator('#heard-load').click();
  await page.waitForFunction(()=>document.querySelector('#version-select').value==='lsg');
  assert.equal(program().length,afterManual);
  results.push('versions concurrentes : sélecteur libéré, avertissement actualisé, aucune diffusion');
  // Arrêt au relais : une réponse déjà partie ne doit pas refaire apparaître la carte.
  const admin=new WebSocket(`ws://127.0.0.1:${port}/verseobs-relay`,{headers:{Origin:base}});
  await new Promise(r=>admin.once('open',r));
  admin.send(JSON.stringify({type:'caption_admin',action:'stop',id:'stop-'+Date.now()}));
  await page.waitForFunction(()=>document.querySelector('#heard-proposal').hidden);
  say(); await sleep(100);
  assert.equal(await page.locator('#heard-proposal').isVisible(),false);
  admin.close();
  results.push('arrêt : réponse en vol bloquée');
  clearInterval(heartbeat);ws.close();
  await page.waitForFunction(()=>document.querySelector('#heard-state').textContent==='En attente');
  assert.equal(await page.locator('#heard-proposal').isVisible(),false);
  results.push('perte du service : proposition retirée');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'browser-heard.json'),JSON.stringify({chromium:browser.version(),results,errors,programCommands:program().map(x=>x.type)},null,2));
  console.log(results.map(x=>'ok   '+x).join('\n'));
} finally {
  clearInterval(heartbeat);ws.terminate();
  await ctx.close();await obsctx.close();await browser.close();
  await new Promise(r=>server.close(r));
}
